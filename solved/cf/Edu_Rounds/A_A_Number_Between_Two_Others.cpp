#define endl '\n'

void solve() {
    int n, m;
    cin >> n >> m;
    for (int i = n * 2; i < m; i += n) {
        if (m % i){
            cout << "YES\n";
            return;
        }
    }
    cout << "NO" << endl;
}

int32_t main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t; 
    while (t--) solve();
    return 0;
}
